"""Screen heads with known warps, then select using actual synthetic tracking.

Every target trajectory is generated by an image transformation. The program
never reads DAVIS human trajectory annotations during selection.
"""
import argparse
import json
from pathlib import Path

import numpy as np

from research_summarize import load_probe


def candidates(root, count):
    destination = root/"results/closed_loop_candidates.json"
    if destination.exists():
        return json.loads(destination.read_text())
    records = []
    for transform in ("translate", "translate_appearance"):
        records += load_probe(root/f"results/probe_wan_{transform}_t25")
    names = records[0]["variant_names"].tolist()
    scores = np.mean([r["score"] for r in records], 0)[:, :, names.index("post_full")]
    chosen = np.argsort(scores.ravel())[-count:][::-1]
    heads = [{"layer": int(i)//scores.shape[1], "head": int(i)%scores.shape[1],
              "screening_score": float(scores.ravel()[i]*100)} for i in chosen]
    payload = {"heads": heads, "count": count, "criterion": "top heads by mean known-warp post-RoPE direct PCK",
               "uses_human_trajectory_annotations": False,
               "tracking_candidates": ["post_full", "post_low15", "time_removed", "post_centered"],
               "tracking_preset": {"argmax_radius": 16, "search_radius": 48, "visibility_threshold": 24, "ema": .05}}
    destination.write_text(json.dumps(payload, indent=2))
    return payload


def prepare(root):
    target = root/"closed_loop_calibration"
    features = target/"features/known_warps"
    annotations = target/"data/davis_records"
    features.mkdir(exist_ok=True, parents=True)
    annotations.mkdir(exist_ok=True, parents=True)
    (target/"scripts").mkdir(exist_ok=True)
    evaluator = target/"scripts/tapvid_official_evaluation_datasets.py"
    if not evaluator.exists():
        evaluator.symlink_to(root/"scripts/tapvid_official_evaluation_datasets.py")
    y, x = np.meshgrid(np.linspace(.2, .8, 5), np.linspace(.2, .8, 5), indexing="ij")
    points = np.stack((x.ravel(), y.ravel()), -1).astype(np.float32)
    manifest = []
    for transform in ("translate", "translate_appearance"):
        source = root/"features"/f"wan_{transform}_t25_top16"
        for path in sorted(source.glob("*.safetensors")):
            m = json.loads(path.with_suffix(".json").read_text())
            name = f"{m['video']}__{transform}"
            destination = features/f"{name}.safetensors"
            if not destination.exists():
                destination.symlink_to(path)
            h, w = m["source_size"]
            shifts = np.array(m["shifts"], dtype=np.float32) / np.array([w, h], np.float32)
            trajectories = points[:, None] + shifts[None]
            visible = ((trajectories > .001) & (trajectories < .999)).all(-1)
            np.savez_compressed(annotations/f"{name}.annotations.npz", points=trajectories, occluded=~visible)
            m.update(video=name, split="calibration", annotation_source="known image warp; no human tracks")
            destination.with_suffix(".json").write_text(json.dumps(m, indent=2))
            manifest.append({"name": name, "frames": m["frames"], "points": len(points), "split": "calibration"})
    assert len(manifest) == 14, len(manifest)
    (annotations/"manifest.json").write_text(json.dumps(manifest, indent=2))


def freeze(root):
    output = root/"results/frozen_closed_loop_choices.json"
    if output.exists():
        raise FileExistsError(output)
    groups = {}
    source = root/"closed_loop_calibration/results/tracking_known_warps"
    for path in source.glob("*.json"):
        r = json.loads(path.read_text())
        key = (r["layer"], r["head"], r["variant"][0])
        groups.setdefault(key, []).append(r)
    payload = []
    for key, records in groups.items():
        assert len(records) == 14, (key, len(records))
        payload.append({"layer": key[0], "head": key[1], "variant": key[2], "videos": len(records),
                        "aj": float(np.mean([r["metrics"]["average_jaccard"] for r in records])),
                        "coordinate_accuracy": float(np.mean([r["metrics"]["average_pts_within_thresh"] for r in records]))})
    assert len(payload) == 64, len(payload)
    ranked = sorted(payload, key=lambda r: (r["aj"], r["coordinate_accuracy"]), reverse=True)
    output.write_text(json.dumps({"selected": ranked[0], "ranking": ranked,
                                 "uses_human_annotations": False, "objective": "actual tracker AJ on known synthetic warps",
                                 "tracking_constants": "fixed geometric grid preset", "synthetic_images": 7,
                                 "warning": "Developed after DAVIS diagnostic results. Independent transfer check is PointOdyssey, whose results were not used."}, indent=2))
    print(json.dumps(ranked[:10], indent=2))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", choices=["candidates", "prepare", "freeze"])
    parser.add_argument("--root", type=Path, default=Path("/share/yty/heft"))
    parser.add_argument("--count", type=int, default=16)
    args = parser.parse_args()
    if args.mode == "candidates":
        print(json.dumps(candidates(args.root, args.count), indent=2))
    elif args.mode == "prepare":
        prepare(args.root)
    else:
        freeze(args.root)


if __name__ == "__main__":
    main()
